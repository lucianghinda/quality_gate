    def test_agents_section_template_contains_the_agent_contract_markers_commands_and_exit_codes
      with_rendered_template("agents_section.md.tt") do |content, destination_root|
        assert_includes content, "<!-- quality_gate agent contract — start -->"
        assert_includes content, "<!-- quality_gate agent contract — end -->"
        QUALITY_GATE_COMMANDS.each { assert_includes content, _1 }
        assert_match(/Claude Code hooks.*verify.*automatically.*session end/i, content)
        assert_match(/other clients.*Codex.*verify.*manually/i, content)
        assert_includes content, "Fix findings before you continue editing."
        assert_match(/exit 0.*clean/i, content)
        assert_match(/exit 1.*finding/i, content)
        assert_match(/exit 2.*tool failure/i, content)
        assert_match(/10-second/i, content)
        assert_match(/120-second/i, content)
        assert_match(/hook.*unavailable/i, content)
        assert_includes content, "bin/rails generate quality_gate:install --agents"
        refute_includes content, destination_root
      end
    end

    private

    def with_rendered_template(template_name)
      with_destination_root do |destination_root|
        yield render_template(template_name, destination_root), destination_root
      end
    end

    def with_destination_root(&)
      Dir.mktmpdir("quality-gate-generator", &)
    end

    def render_template(template_name, destination_root)
      source = File.join(InstallGenerator.source_root, template_name)
      assert File.file?(source), "expected generator template at #{source}"

      destination = File.join("rendered", template_name.delete_suffix(".tt"))
      generator = InstallGenerator.new([], {}, destination_root: destination_root)
      generator.template(template_name, destination, verbose: false)
      File.read(File.join(destination_root, destination))
    end

    def write_migration(destination_root, filename)
      directory = File.join(destination_root, "db/migrate")
      FileUtils.mkdir_p(directory)
      File.write(File.join(directory, filename), "# migration fixture\n")
    end

    def uncomment(content)
      content.lines.map { _1.sub(/\A# ?/, "") }.join
    end

    def stringify_keys(value)
      case value
      when Hash
        value.to_h { |key, child| [key.to_s, stringify_keys(child)] }
      when Array
        value.map { stringify_keys(_1) }
      else
        value
      end
    end

    def bullet_settings(content, destination_root, environment)
      path = File.join(destination_root, "rendered_bullet.rb")
      File.write(path, content)
      stdout, stderr, status = Open3.capture3(RbConfig.ruby, "-e", bullet_probe, path, environment)
      assert_predicate status, :success?, stderr

      JSON.parse(stdout)
    end

    def bullet_probe
      <<~'RUBY'
        require "json"
        require "bullet"

        Environment = Struct.new(:name) do
          def test? = name == "test"
          def development? = name == "development"
        end

        Config = Struct.new(:unused) do
          def after_initialize(&block) = block.call
        end

        Application = Struct.new(:config)

        module Rails
          class << self
            attr_accessor :application, :env
          end
        end

        module Bullet
          class << self
            attr_accessor :enable, :bullet_logger, :rails_logger
            attr_writer :raise

            def raise = @raise
          end
        end

        Rails.env = Environment.new(ARGV.fetch(1))
        Rails.application = Application.new(Config.new)
        load ARGV.fetch(0)

        puts JSON.generate(
          enable: Bullet.enable,
          raise: Bullet.raise,
          bullet_logger: Bullet.bullet_logger,
          rails_logger: Bullet.rails_logger
        )
      RUBY
    end

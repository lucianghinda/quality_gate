      with_rendered_template("claude_settings.json.tt") do |content, destination_root|
        parsed = JSON.parse(content)
        hooks = parsed.fetch("hooks")

        assert_equal ["hooks"], parsed.keys
        assert_equal %w[PostToolUse Stop], hooks.keys
        assert_equal(

          # Generated by Quality Gate.
        RUBY
      end
    end

    def test_strong_migrations_template_normalizes_zero_padded_versions_to_valid_ruby
      with_destination_root do |destination_root|
        write_migration(destination_root, "007_create_accounts.rb")
        write_migration(destination_root, "008_add_index.rb")

        content = render_template("strong_migrations.rb.tt", destination_root)
        stdout, stderr, status = Open3.capture3(RbConfig.ruby, "-c", stdin_data: content)

        assert_predicate status, :success?, "#{stdout}#{stderr}"
        assert_equal <<~RUBY, content
          # frozen_string_literal: true

          require 'strong_migrations'

          # Generated by Quality Gate.
          StrongMigrations.start_after = 8
        RUBY
      end
    end


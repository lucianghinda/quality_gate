module QualityGate
  class InstallGeneratorTemplatesTest < Minitest::Test
    QUALITY_GATE_COMMANDS = [
      "bundle exec quality_gate fast",
      "bundle exec quality_gate verify",
      "bundle exec quality_gate audit"
    ].freeze
    def test_settings_template_is_inert_and_documents_the_current_defaults
      with_rendered_template("quality_gate.yml.tt") do |content, destination_root|
        assert_nil YAML.safe_load(content)
        assert(content.lines.reject { _1.strip.empty? }.all? { _1.start_with?("#") })
        expected = Config.defaults.reject { |key, _value| key == :gates }
        assert_equal stringify_keys(expected), YAML.safe_load(uncomment(content))
        refute_includes content, destination_root
      end
    end

    def test_settings_template_explains_how_to_disable_coverage_budgets
      with_rendered_template("quality_gate.yml.tt") do |content|
        assert_includes content, "Leave the entire mapping commented to disable coverage budgeting."
      end
    end

    def test_rubocop_template_contains_only_the_host_inheritance_rule
      with_rendered_template("rubocop.yml.tt") do |content, destination_root|
        assert_equal "inherit_gem: { quality_gate: config/rubocop.yml }\n", content
        refute_includes content, destination_root
      end
    end

    def test_bullet_template_enables_only_test_and_development
      with_rendered_template("bullet.rb.tt") do |content, destination_root|
        assert_equal true, bullet_settings(content, destination_root, "test").fetch("enable")
        assert_equal true, bullet_settings(content, destination_root, "development").fetch("enable")
        assert_equal false, bullet_settings(content, destination_root, "production").fetch("enable")
      end
    end

    def test_bullet_template_requires_bullet_before_using_its_constant
      with_rendered_template("bullet.rb.tt") do |content|
        assert content.start_with?(<<~RUBY)
          # frozen_string_literal: true

          require 'bullet'

          Rails.application.config.after_initialize do
        RUBY
      end
    end

    def test_bullet_template_raises_only_in_test
      with_rendered_template("bullet.rb.tt") do |content, destination_root|
        assert_equal true, bullet_settings(content, destination_root, "test").fetch("raise")
        assert_equal false, bullet_settings(content, destination_root, "development").fetch("raise")
        assert_equal false, bullet_settings(content, destination_root, "production").fetch("raise")
      end
    end

    def test_bullet_template_logs_only_in_development
      with_rendered_template("bullet.rb.tt") do |content, destination_root|
        logging = %w[test development production].to_h do |environment|
          settings = bullet_settings(content, destination_root, environment)
          [environment, settings.values_at("bullet_logger", "rails_logger")]
        end

        assert_equal [false, false], logging.fetch("test")
        assert_equal [true, true], logging.fetch("development")
        assert_equal [false, false], logging.fetch("production")
      end
    end

    def test_bullet_template_uses_the_after_initialize_boundary_without_host_values
      with_rendered_template("bullet.rb.tt") do |content, destination_root|
        assert_includes content, "Rails.application.config.after_initialize do"
        refute_includes content, destination_root
      end
    end

    def test_strong_migrations_template_uses_the_newest_migration_version
      with_destination_root do |destination_root|
        write_migration(destination_root, "20250101000000_create_accounts.rb")
        write_migration(destination_root, "20260202000000_add_status_to_accounts.rb")

        content = render_template("strong_migrations.rb.tt", destination_root)

        assert_equal <<~RUBY, content
          # frozen_string_literal: true

          require 'strong_migrations'

          # Generated by Quality Gate.
          StrongMigrations.start_after = 20_260_202_000_000
        RUBY
      end
    end

    def test_strong_migrations_template_requires_strong_migrations_before_using_its_constant
      with_rendered_template("strong_migrations.rb.tt") do |content|
        assert content.start_with?(<<~RUBY)
          # frozen_string_literal: true

